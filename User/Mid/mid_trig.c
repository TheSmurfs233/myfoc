uint8_t mid_trig_init(void)
{
#if (TRIG_MODE == TRIG_MODE_CORDIC)
    bsp_cordic_init();
    return bsp_cordic_self_test();
#else
    return 0u;
#endif
}

void mid_trig_cos_sin(float theta, float *c, float *s)
{
#if (TRIG_MODE == TRIG_MODE_CORDIC)
    bsp_cordic_cos_sin(theta, c, s);
#else
    *s = lut_sin(theta);
    *c = lut_sin(theta + TRIG_HALF_PI);
#endif
}

const char *mid_trig_name(void)
{
#if (TRIG_MODE == TRIG_MODE_CORDIC)
    return "CORDIC";
#else
    return "LUT";
#endif
}


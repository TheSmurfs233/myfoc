/* sin(theta) for any theta, wrapped internally. */
static float lut_sin(float theta)
{
    float    x;
    uint32_t i;
    float    f;

    while (theta >= TRIG_TWO_PI) { theta -= TRIG_TWO_PI; }
    while (theta < 0.0f)         { theta += TRIG_TWO_PI; }

    x = theta * TRIG_RAD_TO_IDX;
    i = (uint32_t)x;
    if (i >= TRIG_TAB_SIZE) { i = TRIG_TAB_SIZE - 1u; }
    f = x - (float)i;

    return s_sin[i] + (s_sin[i + 1u] - s_sin[i]) * f;
}


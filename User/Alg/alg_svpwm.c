/* cos(theta) for any theta, wrapped internally. */
static float cos_lut(float theta)
{
    float    x;
    uint32_t i;
    float    f;

    while (theta >= ALG_TWO_PI) { theta -= ALG_TWO_PI; }
    while (theta < 0.0f)        { theta += ALG_TWO_PI; }

    theta += ALG_HALF_PI;
    if (theta >= ALG_TWO_PI)    { theta -= ALG_TWO_PI; }

    x = theta * ALG_RAD_TO_IDX;
    i = (uint32_t)x;
    if (i >= ALG_TAB_SIZE)      { i = ALG_TAB_SIZE - 1u; }
    f = x - (float)i;

    return s_sin[i] + (s_sin[i + 1u] - s_sin[i]) * f;
}

void alg_svpwm(float theta, float m, float duty[3])
{
    float hi;
    float lo;
    float off;
    uint8_t i;

    if (duty == 0) {
        return;
    }

    duty[0] = 0.5f + 0.5f * m * cos_lut(theta);
    duty[1] = 0.5f + 0.5f * m * cos_lut(theta - ALG_PHASE_120);
    duty[2] = 0.5f + 0.5f * m * cos_lut(theta + ALG_PHASE_120);

    hi = duty[0];
    lo = duty[0];
    for (i = 1u; i < 3u; i++) {
        if (duty[i] > hi) { hi = duty[i]; }
        if (duty[i] < lo) { lo = duty[i]; }
    }

    /* Remove the zero-sequence component: this is the injection that makes it
     * SVPWM instead of plain sinusoidal modulation. */
    off = 0.5f * (hi + lo) - 0.5f;
    for (i = 0u; i < 3u; i++) {
        duty[i] -= off;
    }
}
